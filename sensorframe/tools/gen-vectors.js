#!/usr/bin/env node
// Regenerates the shared golden vectors from tools/vectors.input.json:
//   test-vectors.json             (read by the JS tests and quoted in SPEC.md)
//   arduino/test/test_vectors.h   (read by the C++ tests)
// The C++ tests rebuild every packet with SensorFrameWriter and must match
// these bytes exactly, so the two implementations check each other.
'use strict';

const fs = require('fs');
const path = require('path');
const { createCodec, FMT, frameBytes } = require('../js');

const root = path.join(__dirname, '..');
const input = JSON.parse(fs.readFileSync(path.join(__dirname, 'vectors.input.json'), 'utf8'));
const codec = createCodec();

function jsValue(r) {
  if (r.fmt === 'bytes') return Buffer.from(r.value, 'hex');
  if (r.fmt === 'u64' || r.fmt === 'i64') return BigInt(r.value);
  return r.value;
}

const vectors = input.map((v) => {
  const packet = codec.encode({ ...v.header, records: v.records.map((r) => ({ tag: r.tag, fmt: r.fmt, value: jsValue(r) })) });
  const frame = frameBytes(packet);
  return {
    ...v,
    packetHex: packet.toString('hex'),
    frameHex: frame.toString('hex'),
    crc: '0x' + packet.readUInt16LE(packet.length - 2).toString(16).padStart(4, '0'),
    packetSize: packet.length,
    frameSize: frame.length,
  };
});
fs.writeFileSync(path.join(root, 'test-vectors.json'), JSON.stringify(vectors, null, 2) + '\n');

// ---- C header ----
const bytes = (hex) => (hex.match(/../g) || []).map((b) => '0x' + b).join(', ') || '0';
let h = '// GENERATED by tools/gen-vectors.js from tools/vectors.input.json. Do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n';
h += 'struct TvRecord { uint8_t tag; uint8_t fmt; int64_t i; uint64_t u; double d; const uint8_t* bytes; uint8_t len; };\n';
h += 'struct TvVector { const char* name; uint8_t msgType; uint16_t seq; uint32_t deviceId; uint32_t timestamp;\n';
h += '  const TvRecord* records; size_t recordCount; const uint8_t* packet; size_t packetLen; const uint8_t* frame; size_t frameLen; };\n\n';
vectors.forEach((v, i) => {
  v.records.forEach((r, j) => {
    if (r.fmt === 'bytes') h += `static const uint8_t tv${i}_b${j}[] = { ${bytes(r.value)} };\n`;
  });
  const recs = v.records.map((r, j) => {
    const code = FMT[r.fmt];
    let iv = '0', uv = '0', dv = '0';
    if (r.fmt === 'u64') uv = `${r.value}ULL`;
    else if (r.fmt === 'i64') iv = `${r.value}LL`;
    else if (r.fmt === 'f32' || r.fmt === 'f64') dv = String(r.value);
    else if (r.fmt === 'bool') iv = r.value ? '1' : '0';
    else if (r.fmt !== 'bytes') iv = r.value === -2147483648 ? '(-2147483647LL - 1)' : `${r.value}LL`;
    const b = r.fmt === 'bytes' ? `tv${i}_b${j}, ${r.value.length / 2}` : 'nullptr, 0';
    return `  { ${r.tag}, ${code}, ${iv}, ${uv}, ${dv}, ${b} },`;
  });
  h += `static const TvRecord tv${i}_records[] = {\n${recs.join('\n') || '  { 0, 0, 0, 0, 0, nullptr, 0 },'}\n};\n`;
  h += `static const uint8_t tv${i}_packet[] = { ${bytes(v.packetHex)} };\n`;
  h += `static const uint8_t tv${i}_frame[] = { ${bytes(v.frameHex)} };\n\n`;
});
h += 'static const TvVector TEST_VECTORS[] = {\n';
vectors.forEach((v, i) => {
  h += `  { ${JSON.stringify(v.name)}, ${v.header.msgType}, ${v.header.seq}, ${v.header.deviceId}u, ${v.header.timestamp}u, tv${i}_records, ${v.records.length}, tv${i}_packet, sizeof(tv${i}_packet), tv${i}_frame, sizeof(tv${i}_frame) },\n`;
});
h += '};\nstatic const size_t TEST_VECTOR_COUNT = sizeof(TEST_VECTORS) / sizeof(TEST_VECTORS[0]);\n';
fs.writeFileSync(path.join(root, 'arduino', 'test', 'test_vectors.h'), h);

for (const v of vectors) console.log(`${v.name.padEnd(24)} packet ${String(v.packetSize).padStart(3)} B  frame ${String(v.frameSize).padStart(3)} B  crc ${v.crc}`);
